import { test, expect } from '@playwright/test'
test('filtros, histórico e acesso direto ao NFT', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('status')).toContainText('NFTs encontrados')
  await page.getByRole('button', { name: '2', exact: true }).click()
  await expect(page).toHaveURL(/page=2/)
  const filters = page.getByRole('button', { name: 'Filtros', exact: true })
  if (await filters.isVisible()) await filters.click()
  await page.getByText('Mais filtros', { exact: true }).click()
  await page.getByLabel('Coleção', { exact: true }).selectOption('Original Apes')
  await expect(page.getByRole('button', { name: '1', exact: true })).toHaveAttribute('aria-current', 'page')
  await page.getByRole('searchbox', { name: 'Buscar NFT' }).fill('Emerald')
  await page.getByRole('button', { name: 'Buscar', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('1 NFTs')
  await page.reload()
  await expect(page.getByRole('searchbox')).toHaveValue('Emerald')
  await page.goBack()
  await expect(page.getByRole('searchbox')).toHaveValue('')
  await page.goto('/nfts/emerald-ape-42')
  await expect(page.getByRole('heading', { name: 'Emerald Ape #042', exact: true })).toBeVisible()
  await page.goto('/nfts/nonexistent')
  await expect(page.getByRole('alert')).toContainText('Não foi possível abrir')
})

test('catálogo sem coleção inventada e layout sem overflow', async ({ page }, testInfo) => {
  await page.goto('/')
  await expect(page.getByRole('status')).toContainText('NFTs encontrados')
  await expect(page.getByText('Ecos do Olimpo')).toHaveCount(0)
  await expect(page.getByRole('heading', { name: /Os mitos permanecem/ })).toHaveCount(0)
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  if (testInfo.project.name === 'desktop') {
    await page.setViewportSize({ width: 768, height: 1024 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  }
})

test('arte original do Figma no destaque e no detalhe', async ({ page }) => {
  await page.goto('/')
  const featured = page.locator('.hero-art').getByRole('img')
  await expect(featured).toHaveAttribute('src', /emerald-ape-960\.webp$/)
  await expect.poll(() => featured.evaluate(element => (element as HTMLImageElement).complete && (element as HTMLImageElement).naturalWidth > 0)).toBe(true)
  const nextArtwork = page.getByRole('button', { name: 'Mostrar Sage Nomad #009' })
  await nextArtwork.focus()
  await nextArtwork.press('Enter')
  await expect(nextArtwork).toHaveAttribute('aria-pressed', 'true')
  await expect(featured).toHaveAttribute('src', /sage-nomad-960\.webp$/)
  await page.goto('/nfts/emerald-ape-42')
  const artwork = page.locator('.detail-art').getByRole('img')
  await expect(artwork).toHaveAttribute('src', /emerald-ape-960\.webp$/)
  await expect.poll(() => artwork.evaluate(element => (element as HTMLImageElement).complete && (element as HTMLImageElement).naturalWidth > 0)).toBe(true)
  const zoom = page.getByRole('button', { name: 'Ampliar imagem' })
  await zoom.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('button', { name: 'Reduzir imagem' })).toHaveAttribute('aria-pressed', 'true')
  await page.keyboard.press('Enter')
  await expect(zoom).toHaveAttribute('aria-pressed', 'false')
})

test('faixa de preço combina com busca e persiste na URL', async ({ page }) => {
  await page.goto('/?q=Emerald&collection=Original%20Apes&minPrice=2')
  await expect(page.getByRole('heading', { name: 'Nenhuma obra por aqui.' })).toBeVisible()
  const filters = page.getByRole('button', { name: 'Filtros', exact: true })
  if (await filters.isVisible()) await filters.click()
  await page.getByLabel('Preço mínimo (ETH)').fill('2')
  await page.getByLabel('Preço máximo (ETH)').fill('1')
  await page.getByRole('button', { name: 'Aplicar', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('preço mínimo')
  await page.getByLabel('Preço mínimo (ETH)').fill('1.25')
  await page.getByLabel('Preço máximo (ETH)').fill('1.25')
  await page.getByRole('button', { name: 'Aplicar', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('1 NFTs')
  expect(JSON.parse(new URL(page.url()).searchParams.get('minPrice')!)).toBe('1.25')
  await page.reload()
  await expect(page.getByRole('status')).toContainText('1 NFTs')
  await expect(page.getByRole('searchbox')).toHaveValue('Emerald')
  await page.goto('/?q=Emerald&minPrice=1.250000000000000001')
  await expect(page.getByRole('heading', { name: 'Nenhuma obra por aqui.' })).toBeVisible()
})

test('filtro de rede combina com busca e sobrevive ao refresh', async ({ page }) => {
  await page.goto('/?q=Emerald&network=Polygon')
  await expect(page.getByRole('heading', { name: 'Nenhuma obra por aqui.' })).toBeVisible()
  const filters = page.getByRole('button', { name: 'Filtros', exact: true })
  if (await filters.isVisible()) await filters.click()
  await page.getByRole('button', { name: /Ethereum/ }).click()
  await expect(page.getByRole('status')).toContainText('1 NFTs')
  await page.reload()
  await expect(page.getByRole('status')).toContainText('1 NFTs')
  await expect(page).toHaveURL(/network=Ethereum/)
  await page.goto('/nfts/emerald-ape-42')
  await expect(page.getByText('Ethereum', { exact: true })).toBeVisible()
})

test('vitrines do catálogo alteram os resultados e persistem na URL', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('status')).toContainText('24 NFTs')
  const trending = page.getByRole('button', { name: 'Em alta', exact: true })
  await trending.click()
  await expect(page).toHaveURL(/view=trending/)
  await expect(page.getByRole('status')).toContainText('5 NFTs')
  await page.reload()
  await expect(trending).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('status')).toContainText('5 NFTs')
  await page.getByRole('button', { name: 'Novos lançamentos' }).click()
  await expect(page.getByRole('status')).toContainText('6 NFTs')
  await page.getByRole('button', { name: 'Todos os NFTs' }).click()
  await expect(page.getByRole('status')).toContainText('24 NFTs')
})
