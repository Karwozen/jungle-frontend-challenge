import { test, expect } from '@playwright/test'

test('controle de quantidade respeita limites e calcula o total da edição', async ({ page, isMobile }) => {
  await page.goto('/nfts/emerald-ape-42')
  await page.getByRole('radio', { name: '1/10', exact: true }).check()
  const minus = page.getByRole('button', { name: 'Diminuir quantidade' })
  const plus = page.getByRole('button', { name: 'Aumentar quantidade' })
  await expect(minus).toBeDisabled()
  await plus.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('Quantidade', { exact: true })).toHaveValue('2')
  await expect(plus).toBeDisabled()
  if (isMobile) await expect(page.getByLabel('Total dos itens')).toHaveText('3 ETH')
  await minus.click()
  await expect(page.getByLabel('Quantidade', { exact: true })).toHaveValue('1')
  await expect(minus).toBeDisabled()
})

test('edições têm preço, limite e linhas independentes no carrinho', async ({ page }) => {
  await page.goto('/nfts/emerald-ape-42')
  await page.getByRole('radio', { name: '1/1 — Esgotada' }).check()
  await expect(page.getByRole('button', { name: 'Esgotado', exact: true })).toBeDisabled()
  await page.getByRole('radio', { name: '1/10', exact: true }).check()
  await expect(page.getByLabel('Quantidade', { exact: true })).toHaveAttribute('max', '2')
  await page.getByLabel('Quantidade', { exact: true }).fill('3')
  await expect(page.getByRole('button', { name: 'Adicionar ao carrinho' })).toBeDisabled()
  await page.getByLabel('Quantidade', { exact: true }).fill('2')
  await page.getByRole('button', { name: 'Adicionar ao carrinho' }).click()
  await expect(page.getByText('3.005 ETH', { exact: true })).toBeVisible()
  await page.goto('/nfts/emerald-ape-42')
  await page.getByRole('button', { name: 'Adicionar ao carrinho' }).click()
  await expect(page.getByText('4.255 ETH', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Quantidade de Emerald Ape #042', { exact: true })).toHaveValue('1')
  await expect(page.getByLabel('Quantidade de Emerald Ape #042 — 1/10', { exact: true })).toHaveValue('2')
  await page.getByRole('button', { name: 'Remover Emerald Ape #042 — 1/10', exact: true }).click()
  await expect(page.getByText('1.255 ETH', { exact: true })).toBeVisible()
})

test('estoque e preço de edição recebidos em tempo real atualizam o carrinho', async ({ page }) => {
  await page.goto('/nfts/emerald-ape-42')
  await page.getByRole('radio', { name: '1/10', exact: true }).check()
  await page.getByRole('button', { name: 'Adicionar ao carrinho' }).click()
  await expect(page.getByText('1.505 ETH', { exact: true })).toBeVisible()
  await expect.poll(() => page.evaluate(async () => {
    const response = await fetch('/api/demo/edition-update', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ nftId: 'emerald-ape-42', editionId: 'numbered', price: '1.75', available: 0 }) })
    return response.status
  })).toBe(200)
  await expect(page.getByText('1.755 ETH', { exact: true })).toBeVisible()
  await expect(page.getByRole('alert')).toContainText('disponibilidade mudou')
  const status = await page.evaluate(async () => (await fetch('/api/cart', { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-Guest-Id': localStorage.getItem('kurio.guest')! }, body: JSON.stringify({ nftId: 'emerald-ape-42', editionId: 'numbered', quantity: 1 }) })).status)
  expect(status).toBe(409)
  await page.reload()
  await expect(page.getByRole('alert')).toContainText('disponibilidade mudou')
})
