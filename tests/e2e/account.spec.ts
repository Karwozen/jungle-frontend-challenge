import { test, expect } from '@playwright/test'
test('sessão, logout e isolamento entre dois usuários', async ({ page }) => {
  await page.goto('/account/profile')
  await expect(page).toHaveURL(/\/login/)
  await page.getByLabel('E-mail', { exact: true }).fill('alice@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('Kurio2026!')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page.getByLabel('Nome', { exact: true })).toHaveValue('Alice Colecionadora')
  await page.reload()
  await expect(page.getByLabel('E-mail', { exact: true })).toHaveValue('alice@kurio.test')
  await page.getByRole('button', { name: 'Sair', exact: true }).click()
  await page.goto('/account/profile')
  await page.getByLabel('E-mail', { exact: true }).fill('bruno@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('Kurio2026!')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page.getByLabel('Nome', { exact: true })).toHaveValue('Bruno Colecionador')
  await expect(page.getByLabel('E-mail', { exact: true })).toHaveValue('bruno@kurio.test')
})
test('cadastro, conflito e expiração com retorno', async ({ page }) => {
  await page.goto('/register')
  await page.getByLabel('Nome', { exact: true }).fill('Nova Colecionadora')
  await page.getByLabel('E-mail', { exact: true }).fill('nova@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('NovaSenha2026!')
  await page.getByRole('button', { name: 'Criar conta', exact: true }).click()
  await expect(page).toHaveURL(/\/account\/profile/)
  await expect(page.getByLabel('Nome', { exact: true })).toHaveValue('Nova Colecionadora')
  await page.evaluate(async () => { const token = localStorage.getItem('kurio.session.token'); await fetch('/api/demo/expire-session', { method: 'POST', headers: { Authorization: `Bearer ${token}` } }) })
  await page.reload()
  await expect(page).toHaveURL(/\/login/)
  await page.goto('/register')
  await page.getByLabel('Nome', { exact: true }).fill('Outra Pessoa')
  await page.getByLabel('E-mail', { exact: true }).fill('nova@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('NovaSenha2026!')
  await page.getByRole('button', { name: 'Criar conta', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('já possui uma conta')
})
