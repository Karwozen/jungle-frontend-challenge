import { test, expect } from '@playwright/test'

test('login social simulado cancela e isola os provedores', async ({ page }) => {
  await page.goto('/login?returnTo=%2Faccount%2Fprofile')
  await page.getByRole('button', { name: 'Continuar com Google' }).click()
  await expect(page.getByRole('region', { name: 'Demonstração Google' })).toContainText('perfil fictício')
  await page.getByRole('button', { name: 'Cancelar', exact: true }).click()
  await expect(page).toHaveURL(/login/)
  await page.getByRole('button', { name: 'Continuar com Google' }).click()
  await page.getByRole('button', { name: 'Continuar na demonstração' }).click()
  await expect(page.getByLabel('E-mail', { exact: true })).toHaveValue('demo-google@kurio.test')
  await page.reload()
  await expect(page.getByLabel('E-mail', { exact: true })).toHaveValue('demo-google@kurio.test')
  await page.getByRole('button', { name: 'Sair', exact: true }).click()
  await page.goto('/login')
  await page.getByRole('button', { name: 'Continuar com Facebook' }).click()
  await page.getByRole('button', { name: 'Continuar na demonstração' }).click()
  await expect(page.getByLabel('E-mail', { exact: true })).toHaveValue('demo-facebook@kurio.test')
})

test('categorias combinam com rede e sobrevivem ao refresh', async ({ page, isMobile }) => {
  await page.goto('/')
  if (isMobile) await page.getByRole('button', { name: 'Filtros', exact: true }).click()
  const category = page.getByRole('group', { name: 'Categorias', exact: true }).getByRole('button', { name: /Arte digital/ })
  await category.click()
  await page.getByRole('group', { name: 'Redes', exact: true }).getByRole('button', { name: /Ethereum/ }).click()
  await expect(page).toHaveURL(/category=Arte/)
  await expect(page).toHaveURL(/network=Ethereum/)
  await expect(page.getByRole('status')).toContainText('1 NFTs')
  await page.reload()
  await expect(page.getByRole('status')).toContainText('1 NFTs')
})

test('cadastro confirma senha e apresenta os provedores do Figma', async ({ page }) => {
  await page.goto('/register')
  await page.getByLabel('Nome', { exact: true }).fill('Colecionador')
  await page.getByLabel('E-mail', { exact: true }).fill('novo@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('NovaSenha2026!')
  await page.getByLabel('Confirmar senha', { exact: true }).fill('OutraSenha2026!')
  await page.getByRole('button', { name: /Criar conta|Criar perfil/ }).click()
  await expect(page.getByText('As senhas não coincidem.')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Continuar com Google' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Continuar com Facebook' })).toBeVisible()
  await page.getByRole('button', { name: 'Mostrar senha', exact: true }).first().click()
  await expect(page.getByLabel('Senha', { exact: true })).toHaveAttribute('type', 'text')
})

test('footer informa ações ilustrativas sem simular envio', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('E-mail para novidades').fill('demo@kurio.test')
  await page.getByRole('button', { name: 'Enviar', exact: true }).click()
  await expect(page.getByText('Newsletter ilustrativa. Seu e-mail não foi enviado nem cadastrado.')).toBeVisible()
  await page.getByRole('navigation', { name: 'Central de ajuda' }).getByRole('button', { name: 'Denunciar item' }).click()
  await expect(page.getByRole('dialog', { name: 'Denunciar item' })).toContainText('Nenhuma solicitação foi enviada')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', { name: 'Denunciar item' })).not.toBeVisible()
})

test('registra telas de autenticação e conta para comparação visual', async ({ page }, info) => {
  await page.setViewportSize({ width: info.project.name === 'mobile' ? 414 : 1440, height: info.project.name === 'mobile' ? 896 : 1080 })
  await page.goto('/register')
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Continuar com Google' })).toBeVisible()
  await page.evaluate(() => document.fonts.ready)
  await page.screenshot({ path: `output/figma-register-${info.project.name}.png` })
  await page.goto('/login')
  await page.getByLabel('E-mail', { exact: true }).fill('alice@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('Kurio2026!')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page.getByLabel('Nome', { exact: true })).toHaveValue('Alice Colecionadora')
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: `output/figma-profile-${info.project.name}.png`, fullPage: true })
  await page.getByRole('navigation', { name: 'Conta do colecionador' }).getByRole('link', { name: 'Carteiras', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Salvar carteira' })).toBeVisible()
  await page.screenshot({ path: `output/figma-wallets-${info.project.name}.png`, fullPage: true })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
