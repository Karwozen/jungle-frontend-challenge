import { test, expect } from '@playwright/test'

test('Solana valida carteira, filtra catálogo e confirma compra na mesma rede', async ({ page, isMobile }) => {
  await page.goto('/account/wallets')
  await page.getByLabel('E-mail', { exact: true }).fill('alice@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('Kurio2026!')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/account\/wallets/)
  await page.getByLabel('Nome da carteira').fill('Solana demo')
  await page.getByLabel('Endereço da carteira').fill('0x1111111111111111111111111111111111111111')
  await page.getByLabel('Rede', { exact: true }).selectOption('Solana')
  await page.getByRole('button', { name: 'Salvar carteira' }).click()
  await expect(page.getByRole('alert')).toContainText('endereço Solana válido')
  await page.getByLabel('Endereço da carteira').fill('11111111111111111111111111111112')
  await page.getByRole('button', { name: 'Salvar carteira' }).click()
  await expect(page.getByText('Solana demo · Principal')).toBeVisible()
  await page.goto('/')
  if (isMobile) await page.getByRole('button', { name: 'Filtros', exact: true }).click()
  await page.getByRole('group', { name: 'Redes', exact: true }).getByRole('button', { name: /Solana/ }).click()
  await expect(page).toHaveURL(/network=Solana/)
  await page.reload()
  if (isMobile) await page.getByRole('button', { name: 'Filtros', exact: true }).click()
  await expect(page.getByRole('group', { name: 'Redes', exact: true }).getByRole('button', { name: /Solana/ })).toHaveAttribute('aria-pressed', 'true')
  await page.goto('/nfts/ape-108')
  await expect(page.getByText('Solana', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Adicionar ao carrinho' }).click()
  await page.getByRole('link', { name: 'Continuar para pagamento' }).click()
  await page.getByLabel('Nome de usuário', { exact: true }).fill('alice')
  await page.getByLabel('Nome do perfil', { exact: true }).fill('Alice Solana')
  await page.getByLabel('Código de indicação').fill('KURIO')
  await page.getByLabel('Nome LNS').fill('alice.sol')
  await expect(page.getByLabel('Rede de pagamento')).toHaveValue('Solana')
  await page.getByRole('button', { name: 'Conectar carteira', exact: true }).click()
  await page.getByRole('button', { name: 'Atualizar cotação' }).click()
  await expect(page.getByText('1 × Cosmic Bloom #108')).toBeVisible()
  await page.getByLabel('Endereço da carteira secundária (opcional)').fill('0x1111111111111111111111111111111111111111')
  await page.getByRole('button', { name: 'Revisar compra' }).click()
  await expect(page.getByRole('alert')).toContainText('endereço válido para Solana')
  await page.getByLabel('Endereço da carteira secundária (opcional)').fill('11111111111111111111111111111112')
  await page.getByRole('button', { name: 'Revisar compra' }).click()
  await page.getByRole('button', { name: 'Confirmar pedido' }).click()
  await expect(page.getByRole('heading', { name: 'Pedido confirmado' })).toBeVisible({ timeout: 10000 })
  await expect(page.getByText('Solana demo · Solana')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Pedido confirmado' })).toBeVisible()
})

test('API Solana rejeita bytes inválidos e distingue maiúsculas de minúsculas', async ({ page }) => {
  await page.goto('/login')
  await page.getByLabel('E-mail', { exact: true }).fill('alice@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('Kurio2026!')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/account\/profile/)
  const result = await page.evaluate(async () => {
    const headers = { Authorization: 'Bearer ' + localStorage.getItem('kurio.session.token'), 'Content-Type': 'application/json' }
    const post = (address: string) => fetch('/api/wallets', { method: 'POST', headers, body: JSON.stringify({ label: 'Solana', address, network: 'Solana', primary: false }) })
    const short = await post('z'.repeat(32))
    const zero = await post('0'.repeat(32))
    const first = await post('So11111111111111111111111111111111111111112')
    const second = await post('so11111111111111111111111111111111111111112')
    const duplicate = await post('So11111111111111111111111111111111111111112')
    return [short.status, zero.status, first.status, second.status, duplicate.status]
  })
  expect(result).toEqual([422, 422, 201, 201, 409])
})
