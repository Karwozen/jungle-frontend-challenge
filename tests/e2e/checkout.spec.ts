test('chave repetida não duplica e conteúdo diferente retorna conflito', async ({ page }) => {
  await prepare(page)
  const result = await page.evaluate(async () => {
    const headers = { Authorization: 'Bearer ' + localStorage.getItem('kurio.session.token'), 'Content-Type': 'application/json' }
    const quote = await (await fetch('/api/quotes', { method: 'POST', headers })).json()
    const wallets = await (await fetch('/api/wallets', { headers })).json()
    const input = { quoteId: quote.id, walletId: wallets[0].id, network: 'Ethereum', name: 'Alice', email: 'alice@kurio.test', accepted: true, username: 'alice', profileName: 'Coleção Alice', invitationCode: 'KURIO2026', lnsName: 'alice.eth', walletType: 'WalletConnect', secondaryAddress: '', note: '' }
    const post = (body: unknown) => fetch('/api/orders', { method: 'POST', headers: { ...headers, 'Idempotency-Key': 'double-click' }, body: JSON.stringify(body) })
    const responses = await Promise.all([post(input), post(input)])
    const orders = await Promise.all(responses.map(response => response.json()))
    const conflict = await post({ ...input, name: 'Outra pessoa' })
    const unauthorized = await fetch('/api/orders/' + orders[0].id)
    return { ids: orders.map(order => order.id), conflict: conflict.status, unauthorized: unauthorized.status }
  })
  expect(result.ids[0]).toBe(result.ids[1])
  expect(result.conflict).toBe(409)
  expect(result.unauthorized).toBe(401)
})

test('pedido rejeita rede incompatível e preserva o carrinho', async ({ page }) => {
  await prepare(page)
  const result = await page.evaluate(async () => {
    const headers = { Authorization: 'Bearer ' + localStorage.getItem('kurio.session.token'), 'Content-Type': 'application/json' }
    const wallet = await (await fetch('/api/wallets', { method: 'POST', headers, body: JSON.stringify({ label: 'Polygon', address: '0x2222222222222222222222222222222222222222', network: 'Polygon', primary: false }) })).json()
    const quote = await (await fetch('/api/quotes', { method: 'POST', headers })).json()
    const response = await fetch('/api/orders', { method: 'POST', headers: { ...headers, 'Idempotency-Key': 'rede-incompativel' }, body: JSON.stringify({ quoteId: quote.id, walletId: wallet.id, network: 'Polygon', name: 'Alice', email: 'alice@kurio.test', accepted: true, username: 'alice', profileName: 'Alice', invitationCode: 'KURIO', lnsName: 'alice.eth', walletType: 'WalletConnect', secondaryAddress: '', note: '' }) })
    const error = await response.json()
    const cart = await (await fetch('/api/cart', { headers })).json()
    return { status: response.status, code: error.code, items: cart.items.length }
  })
  expect(result).toEqual({ status: 409, code: 'NETWORK_MISMATCH', items: 1 })
})

