test('compra de edição numerada reduz apenas seu estoque e mantém o recibo', async ({ page }) => {
  await prepare(page, 'success', 'numbered')
  await page.getByRole('button', { name: 'Confirmar pedido' }).click()
  await expect(page).toHaveURL(/checkout\/orders\//)
  await page.evaluate(async () => {
    await fetch('/api/cart', { method: 'POST', headers: { Authorization: 'Bearer ' + localStorage.getItem('kurio.session.token'), 'Content-Type': 'application/json' }, body: JSON.stringify({ nftId: 'emerald-ape-42', editionId: 'standard', quantity: 2 }) })
  })
  await expect(page.getByRole('heading', { name: 'Pedido confirmado' })).toBeVisible({ timeout: 10000 })
  await expect(page.getByText('Edição: 1/10')).toBeVisible()
  await expect(page.getByText('1.505 ETH', { exact: true })).toBeVisible()
  const nft = await page.evaluate(async () => (await fetch('/api/nfts/emerald-ape-42')).json())
  expect(nft.available).toBe(5)
  expect(nft.editions.find((edition: { id: string }) => edition.id === 'numbered').available).toBe(1)
  await page.evaluate(async () => {
    await fetch('/api/demo/edition-update', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ nftId: 'emerald-ape-42', editionId: 'numbered', price: '9.99', available: 0 }) })
  })
  await page.reload()
  await expect(page.getByText('1.505 ETH', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Voltar ao carrinho' }).click()
  await expect(page.getByLabel('Quantidade de Emerald Ape #042', { exact: true })).toHaveValue('2')
  await expect(page.getByText('Edição: 1/10')).toHaveCount(0)
})
