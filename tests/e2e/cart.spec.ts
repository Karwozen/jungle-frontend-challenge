import { test, expect } from '@playwright/test'
test('controles do carrinho atualizam quantidade e total e respeitam estoque', async ({ page, isMobile }) => {
  await page.goto('/nfts/emerald-ape-42')
  await page.getByRole('button', { name: 'Adicionar ao carrinho' }).click()
  const minus = page.getByRole('button', { name: 'Diminuir quantidade de Emerald Ape #042 — 1/50' })
  const plus = page.getByRole('button', { name: 'Aumentar quantidade de Emerald Ape #042 — 1/50' })
  await expect(minus).toBeDisabled()
  await plus.click()
  await expect(page.getByLabel('Quantidade de Emerald Ape #042', { exact: true })).toHaveValue('2')
  await expect(page.getByText('2.505 ETH', { exact: true })).toBeVisible()
  await minus.click()
  await expect(page.getByLabel('Quantidade de Emerald Ape #042', { exact: true })).toHaveValue('1')
  await expect(page.getByText('1.255 ETH', { exact: true })).toBeVisible()
  await plus.click()
  await expect(page.getByLabel('Quantidade de Emerald Ape #042', { exact: true })).toHaveValue('2')
  await page.evaluate(async () => {
    await fetch('/api/demo/edition-update', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ nftId: 'emerald-ape-42', editionId: 'standard', available: 1 }) })
  })
  await expect(page.getByRole('alert')).toContainText('disponibilidade mudou')
  await minus.click()
  await expect(page.getByLabel('Quantidade de Emerald Ape #042', { exact: true })).toHaveValue('1')
  await expect(page.getByRole('alert')).toHaveCount(0)
  if (isMobile) await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
test('carrinho visitante persiste ao autenticar e calcula cupom na API', async ({ page }) => {
  await page.goto('/nfts/emerald-ape-42')
  await page.getByLabel('Quantidade', { exact: true }).fill('2')
  await page.getByRole('button', { name: 'Adicionar ao carrinho' }).click()
  await expect(page).toHaveURL(/\/cart/)
  await expect(page.getByText('2.505 ETH', { exact: true })).toBeVisible()
  await page.getByLabel('Cupom promocional').fill('INVALID')
  await page.getByRole('button', { name: 'Aplicar cupom' }).click()
  await expect(page.getByRole('alert')).toContainText('Cupom inválido')
  await page.getByLabel('Cupom promocional').fill('KURIO10')
  await page.getByRole('button', { name: 'Aplicar cupom' }).click()
  await expect(page.getByText('2.255 ETH', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Quantidade de Emerald Ape #042', { exact: true })).toHaveValue('2')
  await page.goto('/login?returnTo=/cart')
  await page.getByLabel('E-mail', { exact: true }).fill('alice@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('Kurio2026!')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/\/cart/)
  await expect(page.getByLabel('Quantidade de Emerald Ape #042', { exact: true })).toHaveValue('2')
  await expect(page.getByText('2.255 ETH', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Remover Emerald Ape #042', exact: true }).click()
  await expect(page.getByText('Seu carrinho está vazio.')).toBeVisible()
})
