import { test, expect } from '@playwright/test'

test('perfil, senha e carteiras persistem e respeitam o usuário', async ({ page }) => {
  await page.goto('/account/profile')
  await expect(page).toHaveURL(/\/login/)
  await page.getByLabel('E-mail', { exact: true }).fill('alice@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('Kurio2026!')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page.getByLabel('Nome', { exact: true })).toHaveValue('Alice Colecionadora')
  await page.getByLabel('Nome', { exact: true }).fill('Alice Olimpiana')
  await page.getByLabel('Nome de usuário', { exact: true }).fill('alice.kurio')
  await page.getByLabel('Nome ENS', { exact: true }).fill('alice')
  await page.getByLabel('Apelido da carteira', { exact: true }).fill('Minha coleção')
  await page.getByLabel('E-mail', { exact: true }).fill('olimpiana@kurio.test')
  await page.getByLabel(/Avatar \(/).setInputFiles({ name: 'avatar.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/aKsAAAAASUVORK5CYII=', 'base64') })
  await expect(page.getByAltText('Avatar do perfil')).toBeVisible()
  await page.getByRole('button', { name: 'Salvar perfil' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Alterações salvas' })).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Nome', { exact: true })).toHaveValue('Alice Olimpiana')
  await expect(page.getByLabel('Nome de usuário', { exact: true })).toHaveValue('alice.kurio')
  await expect(page.getByLabel('Nome ENS', { exact: true })).toHaveValue('alice')
  await expect(page.getByLabel('Apelido da carteira', { exact: true })).toHaveValue('Minha coleção')
  await expect(page.getByAltText('Avatar do perfil')).toBeVisible()
  await page.getByLabel('Senha atual').fill('senha-errada')
  await page.getByLabel('Nova senha', { exact: true }).fill('NovaSenha2026!')
  await page.getByLabel('Confirmar nova senha').fill('NovaSenha2026!')
  await page.getByRole('button', { name: 'Alterar senha' }).click()
  await expect(page.getByRole('alert')).toContainText('Senha atual incorreta')
  await page.getByLabel('Senha atual').fill('Kurio2026!')
  await page.getByRole('button', { name: 'Alterar senha' }).click()
  await expect(page.getByLabel('Senha atual')).toHaveValue('')
  await page.getByRole('navigation', { name: 'Conta do colecionador' }).getByRole('link', { name: 'Carteiras', exact: true }).click()
  await page.getByLabel('Nome da carteira').fill('Olimpo')
  await page.getByLabel('Endereço da carteira').fill('0x1111111111111111111111111111111111111111')
  await page.getByRole('button', { name: 'Salvar carteira' }).click()
  await expect(page.getByText('Olimpo · Principal')).toBeVisible()
  await page.getByLabel('Nome da carteira').fill('Atena')
  await page.getByLabel('Endereço da carteira').fill('0x2222222222222222222222222222222222222222')
  await page.getByLabel('Rede', { exact: true }).selectOption('Polygon')
  await page.getByLabel('Carteira principal').check()
  await page.getByRole('button', { name: 'Salvar carteira' }).click()
  await expect(page.getByText('Atena · Principal')).toBeVisible()
  await page.reload()
  await expect(page.getByText('Olimpo · Secundária')).toBeVisible()
  await expect(page.getByText('Atena · Principal')).toBeVisible()
  await page.getByRole('button', { name: 'Editar Atena' }).click()
  await page.getByLabel('Nome da carteira').fill('Atena editada')
  await page.getByRole('button', { name: 'Salvar carteira' }).click()
  await expect(page.getByText('Atena editada · Principal')).toBeVisible()
  await page.getByRole('button', { name: 'Sair', exact: true }).click()
  await expect(page).toHaveURL(/\/\?/)
  await page.goto('/account/profile')
  await page.getByLabel('E-mail', { exact: true }).fill('olimpiana@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('NovaSenha2026!')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL(/account\/profile/)
  await page.getByRole('navigation', { name: 'Conta do colecionador' }).getByRole('link', { name: 'Carteiras', exact: true }).click()
  await expect(page.getByText('Atena editada · Principal')).toBeVisible()
  await page.getByRole('button', { name: 'Sair', exact: true }).click()
  await expect(page).toHaveURL(/\/\?/)
  await page.goto('/account/profile')
  await page.getByLabel('E-mail', { exact: true }).fill('bruno@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('Kurio2026!')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page.getByLabel('Nome', { exact: true })).toHaveValue('Bruno Colecionador')
  await page.getByRole('navigation', { name: 'Conta do colecionador' }).getByRole('link', { name: 'Carteiras', exact: true }).click()
  await expect(page.getByText('Atena editada · Principal')).toHaveCount(0)
})
